import unittest
from datetime import date
from decimal import Decimal

from app import create_app, db
from app.models import Category, Currency, Receipt, User


class ClearDataTestCase(unittest.TestCase):
    def setUp(self):
        self.app = create_app({
            "TESTING": True,
            "SQLALCHEMY_DATABASE_URI": "sqlite:///:memory:",
            "SQLALCHEMY_TRACK_MODIFICATIONS": False,
        })
        self.client = self.app.test_client()
        self.app_context = self.app.app_context()
        self.app_context.push()
        db.create_all()

    def tearDown(self):
        db.session.remove()
        db.drop_all()
        self.app_context.pop()

    def test_clear_data_deletes_receipts_and_unused_reference_data(self):
        user = User.query.filter_by(email="demo@example.com").first()
        self.assertIsNotNone(user)

        category = Category(category_name="Food", description="Autogenerated")
        currency = Currency(currency_code="MYR", currency_name="MYR Currency")
        db.session.add(category)
        db.session.add(currency)
        db.session.flush()

        receipt = Receipt(
            user_id=user.user_id,
            merchant_name="Store",
            receipt_date=date.today(),
            total_amount=Decimal("50.00"),
            amount_in_sgd=Decimal("14.30"),
            currency_code=currency.currency_code,
            category_id=category.category_id,
            receipt_image_path="uploads/test.png",
        )
        db.session.add(receipt)
        db.session.commit()

        response = self.client.post("/api/clear-data")
        self.assertEqual(response.status_code, 200)

        payload = response.get_json()
        self.assertEqual(payload["status"], "success")
        self.assertEqual(payload["data"]["deletedReceipts"], 1)

        self.assertEqual(Receipt.query.count(), 0)
        self.assertEqual(Category.query.count(), 0)
        self.assertEqual(Currency.query.count(), 0)
        self.assertGreaterEqual(User.query.count(), 1)

        dashboard_response = self.client.get(f"/api/dashboard?user_id={user.user_id}")
        self.assertEqual(dashboard_response.status_code, 200)
        dashboard_payload = dashboard_response.get_json()
        self.assertEqual(dashboard_payload["totalExpenses"], 0)
        self.assertEqual(dashboard_payload["monthlySpending"], 0)
        self.assertEqual(dashboard_payload["receiptCount"], 0)
        self.assertEqual(dashboard_payload["largestExpense"], "-")


if __name__ == "__main__":
    unittest.main()
