import os
from datetime import datetime
from flask import Blueprint, jsonify, request
from werkzeug.utils import secure_filename
from app import db
from app.models import User, Category, Currency, Receipt
from app.services import extract_receipt_data

api_bp = Blueprint('api', __name__)

# Configure Upload Folder
UPLOAD_FOLDER = os.path.join(os.getcwd(), 'uploads')
os.makedirs(UPLOAD_FOLDER, exist_ok=True) # Creates the folder if it doesn't exist

ALLOWED_EXTENSIONS = {'png', 'jpg', 'jpeg', 'webp'}

def allowed_file(filename):
    return '.' in filename and filename.rsplit('.', 1)[1].lower() in ALLOWED_EXTENSIONS

@api_bp.route('/status', methods=['GET'])
def health_check():
    return jsonify({
        "status": "success",
        "message": "AI Receipt & Expense Tracker API is running perfectly."
    }), 200

@api_bp.route('/upload', methods=['POST'])
def upload_receipt():
    # 1. Validate the Request
    if 'file' not in request.files:
        return jsonify({"error": "No file part in the request"}), 400
    
    file = request.files['file']
    user_id = request.form.get('user_id')

    if file.filename == '':
        return jsonify({"error": "No selected file"}), 400
        
    if not user_id:
        return jsonify({"error": "user_id is required"}), 400

    # Ensure user exists before processing
    user = db.session.get(User, user_id)
    if not user:
        return jsonify({"error": "Invalid user_id"}), 404

    # 2. Save the File Locally
    if file and allowed_file(file.filename):
        # Create a unique filename to prevent overwriting
        filename = secure_filename(f"{int(datetime.utcnow().timestamp())}_{file.filename}")
        file_path = os.path.join(UPLOAD_FOLDER, filename)
        file.save(file_path)
        
        # 3. Call the AI Extraction Service
        try:
            extracted_data = extract_receipt_data(file_path)
        except Exception as e:
            return jsonify({"error": str(e)}), 500
            
        # Safely extract data from the AI response
        merchant_name = extracted_data.get('merchant_name')
        receipt_date_str = extracted_data.get('receipt_date')
        total_amount = extracted_data.get('total_amount')
        currency_code = extracted_data.get('currency_code') or 'USD' # Default to USD if null
        category_name = extracted_data.get('category_name') or 'Uncategorized'
        
        # Parse date string to Python Date object
        try:
            receipt_date = datetime.strptime(receipt_date_str, '%Y-%m-%d').date() if receipt_date_str else None
        except ValueError:
            receipt_date = None

        # 4. Database Operations
        try:
            # Check if Currency exists, otherwise create it
            currency = db.session.get(Currency, currency_code)
            if not currency:
                currency = Currency(
                    currency_code=currency_code,
                    currency_name=f"{currency_code} Currency" # Fallback name
                )
                db.session.add(currency)
            
            # Check if Category exists, otherwise create it
            category = Category.query.filter_by(category_name=category_name).first()
            if not category:
                category = Category(
                    category_name=category_name,
                    description="Auto-generated by AI"
                )
                db.session.add(category)
                db.session.flush() # Flush to get category.category_id before committing Receipt
            
            # Create the Receipt record
            new_receipt = Receipt(
                user_id=user.user_id,
                merchant_name=merchant_name,
                receipt_date=receipt_date,
                total_amount=total_amount,
                currency_code=currency.currency_code,
                category_id=category.category_id,
                receipt_image_path=file_path
            )
            
            db.session.add(new_receipt)
            db.session.commit()
            
            # 5. Return Success Response
            return jsonify({
                "status": "success",
                "message": "Receipt processed and saved successfully.",
                "data": {
                    "receipt_id": new_receipt.receipt_id,
                    "merchant_name": merchant_name,
                    "receipt_date": receipt_date_str,
                    "total_amount": total_amount,
                    "currency": currency_code,
                    "category": category_name
                }
            }), 201

        except Exception as e:
            db.session.rollback()
            return jsonify({"error": f"Database error: {str(e)}"}), 500

    return jsonify({"error": "Invalid file type. Allowed types: png, jpg, jpeg, webp"}), 400